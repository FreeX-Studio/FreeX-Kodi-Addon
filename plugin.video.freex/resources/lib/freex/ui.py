LAND_HUBS = ("continue", "upnext")


def icon(name):
    return os.path.join(MEDIA, "icon-%s.png" % name)


def duration_text(ms):
    minutes = int(round((ms or 0) / 60000.0))
    if minutes <= 0:
        return ""
    hours, minutes = divmod(minutes, 60)
    return ("%d h %d min" % (hours, minutes)) if hours else ("%d min" % minutes)


def count(n, one, many):
    return tr(one) if n == 1 else tr(many, n)


def language_name(track):
    """The name of a track's language ("German" for "ger"), as Kodi knows it."""
    code = track.get("languageName") or track.get("language") or ""
    if len(code) in (2, 3):
        try:
            return xbmc.convertLanguage(code, xbmc.ENGLISH_NAME) or code
        except (TypeError, ValueError, RuntimeError):
            return code
    return code


def episode_code(it):
    return "S%s E%s" % (it.get("seasonIndex", "?"), it.get("index", "?"))


