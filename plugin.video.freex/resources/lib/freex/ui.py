def card(api, it, in_season=False):
    """
    A list item for a card: the two lines below the artwork, artwork and the marks on it. Episodes
    show their show and number; inside their season the number and title.
    """
    t = it.get("type")
    if t in ("collection", "playlist"):
        li = xbmcgui.ListItem(it.get("title") or "", offscreen=True)
        li.setLabel2(tr(30087, it.get("childCount") or 0) if it.get("childCount") else "")
        if t == "collection":
            poster, backdrop = api.collection_art(it["id"], "poster"), api.collection_art(it["id"], "backdrop")
        else:
            first = it.get("firstItemId")
            poster = api.art(first, "poster") if first else ""
            backdrop = api.art(first, "backdrop") if first else ""
        li.setArt({"freexposter": poster, "freexland": backdrop, "fanart": backdrop})
        li.setProperty("kind", t)
        return li
    _, li, _ = items.build(api, it, with_menu=False)
    title = it.get("title") or ""
    sub = ""
    if t == "episode" and in_season:
        title = "%s. %s" % (it.get("index", "?"), it.get("title") or "")
        sub = duration_text((it.get("media") or {}).get("durationMs"))
    elif t == "episode":
        title = it.get("showTitle") or title
        sub = "%s, %s" % (episode_code(it), it.get("title") or "")
    elif t == "season":
        sub = count(it["leafCount"], 30099, 30087) if it.get("leafCount") else ""
    elif t in ("movie", "show"):
        sub = str(it.get("year") or "")
    elif t == "extra":
        sub = it.get("ownerTitle") or ""
    li.setLabel(title)
    li.setLabel2(sub)

    show = {"id": it.get("showId"), "artVersion": it.get("artVersion")} if it.get("showId") else None
    if t == "episode":
        poster = api.art({"id": it["seasonId"], "artVersion": it.get("artVersion")} if it.get("seasonId") else show or it,
                         "poster")
        land = api.art(it, "thumb")
    elif t == "extra":
        poster = land = api.art(it, "thumb")
    else:
        poster = api.art(it, "poster")
        land = api.art(it, "backdrop")
    li.setArt({"freexposter": poster, "freexland": land})

    p = it.get("progress") or {}
    if t in ("movie", "episode"):
        if p.get("watched"):
            li.setProperty("done", "true")
        elif not p.get("offsetMs"):
            li.setProperty("corner", "true")
    elif t in ("show", "season"):
        leaves = int(it.get("leafCount") or 0)
        viewed = int(it.get("viewedLeafCount") or 0)
        if leaves and viewed >= leaves:
            li.setProperty("done", "true")
        elif viewed:
            li.setProperty("badge", str(leaves - viewed))
        elif leaves:
            li.setProperty("corner", "true")
    li.setProperty("kind", t or "")
    return li


def face(api, person):
    li = xbmcgui.ListItem(person.get("name") or "", offscreen=True)
    li.setLabel2(person.get("role") or "")
    if person.get("hasImage") and person.get("id"):
        li.setArt({"thumb": api.person_image(person["id"])})
    return li


class UiPlayer(xbmc.Player):
    """Reloads the open windows when a playback started from them ends."""

    def __init__(self):
        super().__init__()
        self.windows = []

    def _refresh(self):
        # The service sends the final position; read the data once it is on the server (at most 4 s).
        win = xbmcgui.Window(utils.HOME_WINDOW)
        monitor = xbmc.Monitor()
        for _ in range(40):
            if win.getProperty(utils.SAVED_PROPERTY) or monitor.waitForAbort(0.1):
                break
        for w in list(self.windows):
            try:
                w.refresh()
            except (ApiError, RuntimeError) as e:
                utils.log("Refresh after playback: %s" % e)

    def onPlayBackStopped(self):  # noqa: N802
        self._refresh()

    def onPlayBackEnded(self):  # noqa: N802
        self._refresh()


def skin_args(name):
    return (name, utils.ADDON_PATH, "Default", "1080i")


