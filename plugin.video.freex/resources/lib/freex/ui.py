class Home(xbmcgui.WindowXML):
    def __new__(cls, *args, **kwargs):  # pylint: disable=unused-argument
        return super().__new__(cls, *skin_args("freex-main.xml"))

    def __init__(self, *args, **kwargs):  # pylint: disable=super-init-not-called,unused-argument
        # Kodi's WindowXML is set up in __new__; its __init__ takes the file arguments again.
        self.api = None
        self.player = None
        self.started = False
        self.entries = []  # sidebar: (key, value)
        self.rows = {}  # list id -> items
        self.grid = []
        self.chips = []
        self.view = None  # (kind, args) of what is shown
        self.history = []

    def setup(self, api, player):
        self.api = api
        self.player = player

    # ---------------------------------------------------------------- setup

    def onInit(self):  # noqa: N802
        if self.started:
            return
        self.started = True
        user = (utils.load_state().get("user") or {}).get("username") or ""
        self.setProperty("freex.user", user)
        self.build_sidebar()
        self.show("home")

    def build_sidebar(self):
        self.entries = [("home", None, tr(30001), "home"), ("watchlist", None, tr(30002), "bookmark"),
                        ("playlists", None, tr(30003), "list"), ("search", None, tr(30004), "search")]
        try:
            for lib in self.api.libraries():
                self.entries.append(("library", lib, lib.get("name") or "?", "tv" if lib.get("type") == "shows" else "movie"))
        except ApiError as e:
            utils.notify(e.message, error=True)
        self.entries += [("settings", None, tr(30018), "gear"), ("close", None, tr(30097), "exit")]
        lst = self.getControl(100)
        lst.reset()
        for key, value, text, ic in self.entries:
            li = xbmcgui.ListItem(text, offscreen=True)
            li.setArt({"icon": icon(ic)})
            li.setProperty("key", key)
            lst.addItem(li)

    def mark_active(self, index):
        lst = self.getControl(100)
        for i in range(lst.size()):
            lst.getListItem(i).setProperty("active", "true" if i == index else "")

    # ---------------------------------------------------------------- views

    def show(self, kind, arg=None, remember=False, focus=True):
        """Shows a view: home, watchlist, playlists, search, library, collection, playlist."""
        if remember and self.view:
            self.history.append(self.view)
        self.view = (kind, arg)
        try:
            if kind == "home":
                self.show_home(focus)
            elif kind == "watchlist":
                self.show_grid(tr(30002), self.api.watchlist(), focus=focus)
            elif kind == "playlists":
                self.show_grid(tr(30003), self.api.playlists(), focus=focus)
            elif kind == "search":
                self.show_search(arg, focus)
            elif kind == "library":
                self.show_library(arg, focus)
            elif kind == "collection":
                c = self.api.collection(arg["id"])
                self.show_grid(c.get("title") or arg.get("title") or "", c.get("items") or [], focus=focus)
            elif kind == "playlist":
                p = self.api.playlist(arg["id"])
                self.show_grid(p.get("title") or arg.get("title") or "", p.get("items") or [], focus=focus)
        except ApiError as e:
            self.api_error(e)
        keys = {"home": 0, "watchlist": 1, "playlists": 2, "search": 3}
        if kind in keys:
            self.mark_active(keys[kind])
        elif kind == "library":
            lib = arg[0]
            for i, (k, v, _, _) in enumerate(self.entries):
                if k == "library" and v and v.get("id") == lib.get("id"):
                    self.mark_active(i)

    def refresh(self):
        if self.view:
            self.show(self.view[0], self.view[1], focus=False)

    def show_home(self, focus=True):
        hubs = [h for h in self.api.hubs() if h.get("items")][:ROWS]
        self.setProperty("view", "home")
        self.rows = {}
        first = None
        for i in range(1, ROWS + 1):
            land_list, poster_list = self.getControl(1000 + i), self.getControl(1100 + i)
            hub = hubs[i - 1] if i <= len(hubs) else None
            if not hub:
                self.setProperty("row%d.title" % i, "")
                self.setProperty("row%d.style" % i, "")
                land_list.reset()
                poster_list.reset()
                continue
            its = hub["items"]
            land = hub.get("key") in LAND_HUBS or all(x.get("type") == "episode" for x in its)
            target, other = (land_list, poster_list) if land else (poster_list, land_list)
            other.reset()
            pos = target.getSelectedPosition() if target.size() else 0
            target.reset()
            target.addItems([card(self.api, x) for x in its])
            if 0 < pos < len(its):
                target.selectItem(pos)
            self.rows[target.getId()] = its
            self.setProperty("row%d.title" % i, hub.get("title") or "")
            self.setProperty("row%d.style" % i, "land" if land else "poster")
            first = first or target.getId()
        self.link_rows()
        if not hubs:
            self.setProperty("view", "grid")
            self.fill_grid(tr(30001), [], [])
        if focus and first:
            self.setFocusId(first)

    def link_rows(self):
        """Up and down between the visible rows."""
        ids = [cid for cid in sorted(self.rows, key=lambda c: c % 100)]
        controls = [self.getControl(c) for c in ids]
        for i, c in enumerate(controls):
            if i > 0:
                c.controlUp(controls[i - 1])
            if i < len(controls) - 1:
                c.controlDown(controls[i + 1])

    def show_grid(self, header, its, chips=None, active_chip=None, focus=True):
        self.setProperty("view", "grid")
        self.fill_grid(header, its, chips or [], active_chip)
        if focus:
            self.setFocusId(300 if its else (301 if chips else 100))

    def fill_grid(self, header, its, chips, active_chip=None):
        self.setProperty("header", header)
        self.setProperty("empty", "" if its else tr(30096))
        grid = self.getControl(300)
        pos = grid.getSelectedPosition() if grid.size() and self.grid and self.grid_header == header else 0
        grid.reset()
        grid.addItems([card(self.api, x) for x in its])
        if 0 < pos < len(its):
            grid.selectItem(pos)
        self.grid = its
        self.grid_header = header
        chip_list = self.getControl(301)
        chip_list.reset()
        self.chips = chips
        for i, (text, _) in enumerate(chips):
            li = xbmcgui.ListItem(text, offscreen=True)
            li.setProperty("active", "true" if i == active_chip else "")
            chip_list.addItem(li)
        if chips and active_chip is not None:
            chip_list.selectItem(active_chip)

    grid_header = None

    LIBRARY_FILTERS = (
        (30008, "sort=title"), (30009, "sort=title&watched=unwatched"),
        (30010, "sort=added&order=desc&watched=inProgress"), (30011, "sort=added&order=desc"),
        (30012, "collections"),
    )

    def show_library(self, arg, focus=True):
        lib, chip = arg
        chips = [(tr(sid), q) for sid, q in self.LIBRARY_FILTERS]
        query = chips[chip][1]
        if query == "collections":
            its = [dict(c, type="collection") for c in self.api.library_collections(lib["id"])]
        else:
            its = self.api.library_items(lib["id"], query).get("items") or []
        self.show_grid(lib.get("name") or "", its, chips, chip, focus=focus)

    def show_search(self, text, focus=True):
        if text is None:
            text = xbmcgui.Dialog().input(tr(30059), type=xbmcgui.INPUT_ALPHANUM)
            if not text or len(text.strip()) < 2:
                if self.history:
                    self.view = self.history.pop()
                return
            text = text.strip()
            self.view = ("search", text)
        res = self.api.search(text)
        found = (res.get("movies") or []) + (res.get("shows") or []) + (res.get("episodes") or [])
        self.show_grid('%s: "%s"' % (tr(30004), text), found, focus=focus)

    # ---------------------------------------------------------------- input

    def onClick(self, cid):  # noqa: N802
        try:
            if cid == 100:
                self.sidebar_click(self.getControl(100).getSelectedPosition())
            elif cid == 301:
                kind, arg = self.view
                if kind == "library":
                    self.show(kind, (arg[0], self.getControl(301).getSelectedPosition()))
                    self.setFocusId(301)
            elif cid == 300:
                pos = self.getControl(300).getSelectedPosition()
                if 0 <= pos < len(self.grid):
                    self.open(self.grid[pos])
            elif cid in self.rows:
                pos = self.getControl(cid).getSelectedPosition()
                if 0 <= pos < len(self.rows[cid]):
                    self.open(self.rows[cid][pos])
        except ApiError as e:
            self.api_error(e)

    def sidebar_click(self, index):
        key, value, _, _ = self.entries[index]
        if key == "close":
            self.close()
        elif key == "settings":
            utils.addon().openSettings()
            utils.reload_settings()
        elif key == "library":
            self.history = []
            self.show("library", (value, 0))
        elif key == "search":
            self.show("search", None, remember=True)
        else:
            self.history = []
            self.show(key)

    def open(self, it):
        t = it.get("type")
        if t == "collection":
            self.show("collection", it, remember=True)
        elif t == "playlist" or ("childCount" in it and "firstItemId" in it):
            self.show("playlist", it, remember=True)
        elif t == "extra":
            playback.start(self.api, self.api.item(it["id"]))
        else:
            open_detail(self.api, self.player, it["id"])
            self.refresh()

    def onAction(self, action):  # noqa: N802
        aid = action.getId()
        focus = self.getFocusId()
        if aid in ACTION_BACK:
            if focus == 100:
                self.close()
            elif self.history:
                self.view = self.history.pop()
                self.show(self.view[0], self.view[1])
            else:
                self.setFocusId(100)
        elif aid in ACTION_CONTEXT:
            it = self.focused_item(focus)
            if it and context_menu(self.api, it):
                self.refresh()

    def focused_item(self, cid):
        its = self.grid if cid == 300 else self.rows.get(cid)
        if not its:
            return None
        pos = self.getControl(cid).getSelectedPosition()
        return its[pos] if 0 <= pos < len(its) else None

    def api_error(self, e):
        if e.status == 401:
            session.forget_token()
            utils.notify(tr(30063), error=True)
            self.close()
        else:
            utils.notify(e.message if e.status else tr(30056) + ": " + e.message, error=True)


def context_menu(api, it):
    """Watched and watchlist for a card; True when something changed."""
    t = it.get("type")
    if t not in ("movie", "show", "season", "episode"):
        return False
    if t in ("movie", "episode"):
        watched = bool((it.get("progress") or {}).get("watched"))
    else:
        leaves = int(it.get("leafCount") or 0)
        watched = leaves > 0 and int(it.get("viewedLeafCount") or 0) >= leaves
    options = [(tr(30031) if watched else tr(30030), "watched")]
    if t in ("movie", "show"):
        options.append((tr(30033) if it.get("onWatchlist") else tr(30032), "watchlist"))
    choice = xbmcgui.Dialog().contextmenu([o[0] for o in options])
    if choice < 0:
        return False
    try:
        if options[choice][1] == "watched":
            api.set_watched(it["id"], not watched)
        else:
            api.set_watchlist(it["id"], not it.get("onWatchlist"))
    except ApiError as e:
        utils.notify(e.message, error=True)
        return False
    return True


# ---------------------------------------------------------------------- detail window


def open_detail(api, player, item_id):
    w = Detail()
    w.setup(api, player, item_id)
    player.windows.append(w)
    try:
        w.doModal()
    finally:
        player.windows.remove(w)
        del w


class Detail(xbmcgui.WindowXML):
    BUTTONS = (21, 22, 23, 24)
    ROW_LISTS = {"a": (50, 51, 52), "b": (60, 61, 62)}
    STYLE_INDEX = {"poster": 0, "land": 1, "face": 2}

    def __new__(cls, *args, **kwargs):  # pylint: disable=unused-argument
        return super().__new__(cls, *skin_args("freex-detail.xml"))

    def __init__(self, *args, **kwargs):  # pylint: disable=super-init-not-called,unused-argument
        self.api = None
        self.player = None
        self.item_id = None
        self.it = {}
        self.target = None  # the episode (or the title itself) the main button plays
        self.rows = {}  # list id -> (kind, items)
        self.loaded = False

    def setup(self, api, player, item_id):
        self.api, self.player, self.item_id = api, player, item_id

    def onInit(self):  # noqa: N802
        if not self.loaded:
            self.loaded = True
            self.refresh()
            self.setFocusId(21)

    # ---------------------------------------------------------------- data

    def refresh(self):
        try:
            self.load()
        except ApiError as e:
            utils.notify(e.message, error=True)

    def load(self):
        api = self.api
        it = self.it = api.item(self.item_id)
        t = it.get("type")
        md = it.get("metadata") or {}
        media = it.get("media") or {}
        p = it.get("progress") or {}
        show = {"id": it.get("showId"), "artVersion": it.get("artVersion")} if it.get("showId") else None

        self.setProperty("title", it.get("showTitle") if t in ("season", "episode") and it.get("showTitle") else it.get("title") or "")
        if t == "season":
            sub = it.get("title") or tr(30095, it.get("index"))
        elif t == "episode":
            sub = "%s · %s" % (episode_code(it), it.get("title") or "")
        else:
            sub = str(it.get("year") or "")
        self.setProperty("subtitle", sub)

        meta = []
        if t == "show":
            seasons = [c for c in it.get("children") or [] if c.get("type") == "season"]
            if seasons:
                meta.append(count(len(seasons), 30098, 30088))
            if it.get("leafCount"):
                meta.append(count(it["leafCount"], 30099, 30087))
        elif t == "season":
            if it.get("leafCount"):
                meta.append(count(it["leafCount"], 30099, 30087))
        else:
            d = media.get("durationMs")
            if d:
                meta.append(duration_text(d))
                left = d - (p.get("offsetMs") or 0) if not p.get("watched") else d
                meta.append(tr(30089, time.strftime("%H:%M", time.localtime(time.time() + left / 1000.0))))
        if it.get("rating"):
            # Not every skin font has a star, so the rating is written out.
            meta.append("%.1f / 10" % float(it["rating"]))
        rating = md.get("contentRating") or it.get("contentRating")
        if rating:
            meta.append(rating)
        if md.get("studio"):
            meta.append(md["studio"] if isinstance(md["studio"], str) else ", ".join(md["studio"]))
        self.setProperty("meta", "   ".join(meta))
        self.setProperty("tagline", it.get("tagline") or "")
        self.setProperty("summary", it.get("summary") or "")
        genres = it.get("genres") or ""
        self.setProperty("genres", genres if isinstance(genres, str) else ", ".join(genres))
        self.setProperty("facts", self.facts(it, md, media))

        if t == "episode":
            self.setProperty("art.style", "land")
            self.setProperty("poster", api.art(it, "thumb"))
        elif t == "extra":
            self.setProperty("art.style", "land")
            self.setProperty("poster", api.art(it, "thumb"))
        else:
            self.setProperty("art.style", "poster")
            self.setProperty("poster", api.art(it, "poster"))
        self.setProperty("backdrop", api.art(show or it, "backdrop"))

        # Progress under the poster.
        dur = media.get("durationMs") or 0
        pct = (p.get("offsetMs") or 0) / float(dur) if dur and not p.get("watched") else 0
        self.setProperty("progress", "true" if pct > 0 else "")
        bar = self.getControl(32)
        bar.setWidth(max(1, int(340 * min(1.0, pct))))
        if self.getProperty("art.style") == "land":
            self.getControl(31).setPosition(130, 300)
            bar.setPosition(130, 300)
        else:
            self.getControl(31).setPosition(130, 650)
            bar.setPosition(130, 650)

        self.target = self.play_target(it)
        self.layout_buttons(it)
        self.fill_rows(it, md)

    def facts(self, it, md, media):
        def line(name, value):
            return "[COLOR FF8A97A8]%s[/COLOR]   %s" % (name, value)
        out = []
        if md.get("directors"):
            out.append(line(tr(30090), ", ".join(items._names(md["directors"]))))  # pylint: disable=protected-access
        if md.get("writers"):
            out.append(line(tr(30091), ", ".join(items._names(md["writers"]))))  # pylint: disable=protected-access
        if media and it.get("type") in ("movie", "episode"):
            h = int(media.get("height") or 0)
            res = ("2160p" if h > 1600 else "1080p" if h > 900 else "720p" if h > 600 else "%dp" % h) if h else ""
            video = " ".join(x for x in (res, (media.get("videoCodec") or "").upper(), media.get("hdr") or "") if x)
            if video:
                out.append(line(tr(30092), video))
            audio = media.get("audio") or []
            if audio:
                a = audio[0]
                ch = int(a.get("channels") or 0)
                channels = {1: "1.0", 2: "2.0", 6: "5.1", 8: "7.1"}.get(ch, str(ch) if ch else "")
                text = " ".join(x for x in (language_name(a), (a.get("codec") or "").upper(),
                                            channels) if x)
                if len(audio) > 1:
                    text += "  (+%d)" % (len(audio) - 1)
                out.append(line(tr(30093), text))
            subs = media.get("subtitles") or []
            if subs:
                out.append(line(tr(30094), ", ".join(sorted({language_name(s) or "?" for s in subs}))))
        return "[CR]".join(out)

    def play_target(self, it):
        """What the main button plays: the title, or the episode of a show or season to go on with."""
        t = it.get("type")
        if t in ("movie", "episode", "extra"):
            return it
        if t == "season":
            episodes = [c for c in it.get("children") or [] if c.get("type") == "episode"]
            return next_episode(episodes)
        seasons = [c for c in it.get("children") or [] if c.get("type") == "season"]
        seasons.sort(key=lambda s: (s.get("index") == 0, s.get("index") or 0))
        first = None
        for s in seasons:
            leaves = int(s.get("leafCount") or 0)
            if leaves and int(s.get("viewedLeafCount") or 0) >= leaves and first is not None:
                continue
            episodes = [c for c in self.api.item(s["id"]).get("children") or [] if c.get("type") == "episode"]
            nxt = next_episode(episodes, fallback=False)
            if nxt:
                return nxt
            if first is None and episodes:
                first = episodes[0]
        return first

    def layout_buttons(self, it):
        t = it.get("type")
        target = self.target or {}
        p = target.get("progress") or {}
        resumable = bool(p.get("offsetMs")) and not p.get("watched")
        word = tr(30080) if resumable else tr(30081)
        if target and target is not it and target.get("type") == "episode":
            word += " " + episode_code(target)
        self.setProperty("playlabel", word)
        play = self.getControl(21)
        play.setVisible(bool(target))
        width = 440  # fixed: Kodi keeps the label width of the XML when a button is resized

        if t in ("movie", "episode"):
            watched = bool((it.get("progress") or {}).get("watched"))
        else:
            leaves = int(it.get("leafCount") or 0)
            watched = leaves > 0 and int(it.get("viewedLeafCount") or 0) >= leaves
        self.setProperty("on23", "true" if watched else "")
        self.setProperty("on24", "true" if it.get("onWatchlist") else "")

        visible = [21] if target else []
        if resumable:
            visible.append(22)
        if t != "extra":
            visible.append(23)
        if t in ("movie", "show"):
            visible.append(24)
        x = 560 + (width + 24 if target else 0)
        for cid in (22, 23, 24):
            on = cid in visible
            self.set_button(cid, on, x)
            if on:
                x += 118
        controls = [self.getControl(c) for c in visible]
        for i, c in enumerate(controls):
            c.controlLeft(controls[i - 1] if i > 0 else c)
            c.controlRight(controls[i + 1] if i < len(controls) - 1 else c)
        self.buttons = visible

    def set_button(self, cid, on, x):
        """Moves a round button together with its four icon images (ids cid*10+1 … cid*10+4)."""
        button = self.getControl(cid)
        button.setVisible(on)
        button.setPosition(x, 310)
        for n in range(1, 5):
            self.getControl(cid * 10 + n).setPosition(x + 26, 336)

