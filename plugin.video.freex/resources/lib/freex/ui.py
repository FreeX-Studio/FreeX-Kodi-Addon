    def fill_rows(self, it, md):
        t = it.get("type")
        api = self.api
        rows = []
        cast = md.get("cast") or []
        extras = it.get("extras") or []
        if t == "show":
            seasons = [c for c in it.get("children") or [] if c.get("type") == "season"]
            for s in seasons:
                s.setdefault("showId", it["id"])
                s.setdefault("showTitle", it.get("title"))
                s.setdefault("artVersion", it.get("artVersion"))
            rows.append((count(len(seasons), 30098, 30088), "poster", "season", seasons))
        elif t == "season":
            episodes = [c for c in it.get("children") or [] if c.get("type") == "episode"]
            rows.append((tr(30084), "land", "episode", episodes))
        if extras and t in ("movie", "show"):
            rows.append((tr(30017), "land", "extra", extras))
        if cast:
            rows.append((tr(30085), "face", "person", cast))
        rows = [r for r in rows if r[3]][:2]
        self.rows = {}
        first_ids = []
        for key, row in zip(("a", "b"), rows + [None] * (2 - len(rows))):
            lists = self.ROW_LISTS[key]
            for cid in lists:
                self.getControl(cid).reset()
            if not row:
                self.setProperty("row%s.title" % key, "")
                self.setProperty("row%s.style" % key, "")
                continue
            title, style, kind, its = row
            cid = lists[self.STYLE_INDEX[style]]
            lst = self.getControl(cid)
            if kind == "person":
                lst.addItems([face(api, x) for x in its])
            else:
                lst.addItems([card(api, x, in_season=kind == "episode") for x in its])
            self.rows[cid] = (kind, its)
            self.setProperty("row%s.title" % key, title)
            self.setProperty("row%s.style" % key, style)
            first_ids.append(cid)
        # Navigation: buttons -> row a -> row b.
        buttons = [self.getControl(c) for c in self.buttons]
        lists = [self.getControl(c) for c in first_ids]
        for b in buttons:
            if lists:
                b.controlDown(lists[0])
        for i, lst in enumerate(lists):
            lst.controlUp(lists[i - 1] if i > 0 else (buttons[0] if buttons else lst))
            lst.controlDown(lists[i + 1] if i < len(lists) - 1 else lst)

