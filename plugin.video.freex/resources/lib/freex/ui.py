"""
The FreeX interface: windows of their own in the look of FreeX TV and FreeX Web, independent of
Kodi's skin. The main window has the sidebar (home, watchlist, playlists, search, libraries) and
either the home rows or a grid; the detail window shows a movie, show, season or episode with its
buttons and rows (seasons, episodes, cast, extras). Playback uses Kodi's player; when it ends the
windows read their data again, so progress and watched marks are current.

The window layouts are in resources/skins/Default/1080i (generated by tools/make_windows.py).
"""

